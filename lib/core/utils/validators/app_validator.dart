// এই ক্লাসটি অ্যাপ্লিকেশনের বিভিন্ন ফর্ম ফিল্ডের জন্য 
// ভ্যালিডেশন লজিক প্রদান করে - ইমেইল, পাসওয়ার্ড, ফোন নম্বর ইত্যাদি।
// ------------------------------------------------------------------
class AppValidator {
  // প্রাইভেট কনস্ট্রাক্টর - এই ক্লাসটি ইনস্ট্যান্টিয়েট করা যাবে না
  AppValidator._();

  // ------------------------------------------------------------------
  // validateEmail মেথড - ইমেইল এড্রেস ভ্যালিডেশন চেক করে
  // ------------------------------------------------------------------
  // প্যারামিটার:
  // - value: ভ্যালিডেশন চেক করার ইমেইল স্ট্রিং (nullable)
  // রিটার্ন: ভ্যালিডেশন ইরর মেসেজ (String?) অথবা null যদি ভ্যালিড হয়
  // ভ্যালিডেশন কন্ডিশন:
  //   1. ফিল্ড খালি থাকা যাবে না
  //   2. বৈধ ইমেইল ফরম্যাটে হতে হবে
  // ------------------------------------------------------------------
  static String? validateEmail(String? value) {
    // খালি ফিল্ড চেক
    if (value == null || value.trim().isEmpty) {
      return 'Email is required.';
    }

    // ইমেইল রেগুলার এক্সপ্রেশন প্যাটার্ন
    final emailRegExp = RegExp(r'^[\w\-.]+@([\w-]+\.)+[\w-]{2,4}$');
    
    // ইমেইল ফরম্যাট ভ্যালিডেশন
    if (!emailRegExp.hasMatch(value.trim())) {
      return 'Invalid email address.';
    }

    // ভ্যালিডেশন সফল
    return null;
  }

  // ------------------------------------------------------------------
  // validatePassword মেথড - পাসওয়ার্ড ভ্যালিডেশন চেক করে
  // ------------------------------------------------------------------
  // প্যারামিটার:
  // - value: ভ্যালিডেশন চেক করার পাসওয়ার্ড স্ট্রিং (nullable)
  // রিটার্ন: ভ্যালিডেশন ইরর মেসেজ (String?) অথবা null যদি ভ্যালিড হয়
  // পাসওয়ার্ড রিকোয়ারমেন্ট:
  //   1. কমপক্ষে ৬ ক্যারেক্টার দীর্ঘ
  //   2. কমপক্ষে একটি বড় হাতের অক্ষর (A-Z)
  //   3. কমপক্ষে একটি সংখ্যা (0-9)
  //   4. কমপক্ষে একটি স্পেশাল ক্যারেক্টার
  // ------------------------------------------------------------------
  static String? validatePassword(String? value) {
    // খালি ফিল্ড চেক
    if (value == null || value.trim().isEmpty) {
      return 'Password is required.';
    }

    final trimmed = value.trim();

    // দৈর্ঘ্য চেক (কমপক্ষে ৬ ক্যারেক্টার)
    if (trimmed.length < 6) {
      return 'Password must be at least 6 characters long.';
    }

    // বড় হাতের অক্ষর চেক
    if (!trimmed.contains(RegExp(r'[A-Z]'))) {
      return 'Password must contain at least one uppercase letter.';
    }

    // সংখ্যা চেক
    if (!trimmed.contains(RegExp(r'[0-9]'))) {
      return 'Password must contain at least one number.';
    }

    // স্পেশাল ক্যারেক্টার চেক
    if (!trimmed.contains(RegExp(r'[!@#$%^&*(),.?":{}|<>]'))) {
      return 'Password must contain at least one special character.';
    }

    // ভ্যালিডেশন সফল
    return null;
  }

  // ------------------------------------------------------------------
  // validatePhoneNumber মেথড - ফোন নম্বর ভ্যালিডেশন চেক করে
  // ------------------------------------------------------------------
  // প্যারামিটার:
  // - value: ভ্যালিডেশন চেক করার ফোন নম্বর স্ট্রিং (nullable)
  // রিটার্ন: ভ্যালিডেশন ইরর মেসেজ (String?) অথবা null যদি ভ্যালিড হয়
  // ফোন নম্বর রিকোয়ারমেন্ট:
  //   1. শুধুমাত্র ১০টি সংখ্যা (0-9)
  //   2. অন্য কোনো ক্যারেক্টার (স্পেস, হাইফেন ইত্যাদি) থাকা যাবে না
  // ------------------------------------------------------------------
  static String? validatePhoneNumber(String? value) {
    // খালি ফিল্ড চেক
    if (value == null || value.trim().isEmpty) {
      return 'Phone number is required.';
    }

    // ফোন নম্বর রেগুলার এক্সপ্রেশন (১০ ডিজিট)
    final phoneRegExp = RegExp(r'^\d{10}$');
    
    // ফোন নম্বর ফরম্যাট ভ্যালিডেশন
    if (!phoneRegExp.hasMatch(value.trim())) {
      return 'Invalid phone number (must be 10 digits).';
    }

    // ভ্যালিডেশন সফল
    return null;
  }
}
