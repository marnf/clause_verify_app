import 'package:flutter/material.dart';
import 'package:get/get.dart';
import 'package:intl/intl.dart';

// ------------------------------------------------------------------
// AppHelperFunctions ক্লাস
// ------------------------------------------------------------------
// এই ক্লাসটি অ্যাপ্লিকেশন জুড়ে ব্যবহারযোগ্য সাধারণ হেল্পার ফাংশন 
// প্রদান করে - স্ন্যাকবার, নেভিগেশন, UI ইউটিলিটি ইত্যাদি।
// ------------------------------------------------------------------
class AppHelperFunctions {
  // প্রাইভেট কনস্ট্রাক্টর - এই ক্লাসটি ইনস্ট্যান্টিয়েট করা যাবে না
  AppHelperFunctions._();

  // ------------------------------------------------------------------
  // showSnackBar মেথড - স্ক্রিনে স্ন্যাকবার প্রদর্শন করে
  // ------------------------------------------------------------------
  // প্যারামিটার:
  // - message: প্রদর্শন করার বার্তা
  // ব্যবহার: অস্থায়ী বার্তা প্রদর্শনের জন্য
  // ------------------------------------------------------------------
  static void showSnackBar(String message) {
    ScaffoldMessenger.of(Get.context!).showSnackBar(
      SnackBar(content: Text(message)),
    );
  }

  // ------------------------------------------------------------------
  // showAlert মেথড - অ্যালার্ট ডায়ালগ বক্স প্রদর্শন করে
  // ------------------------------------------------------------------
  // প্যারামিটার:
  // - title: অ্যালার্টের শিরোনাম
  // - message: অ্যালার্টের মূল বার্তা
  // রিটার্ন: কোনো রিটার্ন মান নেই (void)
  // ------------------------------------------------------------------
  static void showAlert(String title, String message) {
    showDialog(
      context: Get.context!,
      builder: (BuildContext context) {
        return AlertDialog(
          title: Text(title),
          content: Text(message),
          actions: [
            TextButton(
              onPressed: () => Navigator.of(context).pop(),
              child: const Text('OK'),
            ),
          ],
        );
      },
    );
  }

  // ------------------------------------------------------------------
  // navigateToScreen মেথড - নতুন স্ক্রিনে নেভিগেট করে
  // ------------------------------------------------------------------
  // প্যারামিটার:
  // - context: বর্তমান BuildContext
  // - screen: নেভিগেট করার লক্ষ্য স্ক্রিন (Widget)
  // ব্যবহার: স্ক্রিন নেভিগেশনের জন্য
  // ------------------------------------------------------------------
  static void navigateToScreen(BuildContext context, Widget screen) {
    Navigator.push(
      context,
      MaterialPageRoute(builder: (_) => screen),
    );
  }

  // ------------------------------------------------------------------
  // truncateText মেথড - নির্দিষ্ট দৈর্ঘ্যের পরে টেক্সট ছোট করে
  // ------------------------------------------------------------------
  // প্যারামিটার:
  // - text: ছোট করা হবে এমন টেক্সট
  // - maxLength: অনুমোদিত সর্বোচ্চ দৈর্ঘ্য
  // রিটার্ন: ছোট করা টেক্সট (প্রয়োজনে '...' যোগ করে)
  // ------------------------------------------------------------------
  static String truncateText(String text, int maxLength) {
    if (text.length <= maxLength) {
      return text;
    } else {
      return '${text.substring(0, maxLength)}...';
    }
  }

  // ------------------------------------------------------------------
  // isDarkMode মেথড - ডার্ক মোড চেক করে
  // ------------------------------------------------------------------
  // প্যারামিটার:
  // - context: বর্তমান BuildContext
  // রিটার্ন: true যদি ডার্ক মোড সক্রিয় থাকে, নতুবা false
  // ------------------------------------------------------------------
  static bool isDarkMode(BuildContext context) {
    return Theme.of(context).brightness == Brightness.dark;
  }

  // ------------------------------------------------------------------
  // স্ক্রিন সাইজ সম্পর্কিত মেথডসমূহ
  // ------------------------------------------------------------------
  // screenSize মেথড - সম্পূর্ণ স্ক্রিনের সাইজ রিটার্ন করে
  // ------------------------------------------------------------------
  static Size screenSize() {
    return MediaQuery.of(Get.context!).size;
  }

  // ------------------------------------------------------------------
  // screenHeight মেথড - স্ক্রিনের উচ্চতা রিটার্ন করে
  // ------------------------------------------------------------------
  static double screenHeight() {
    return MediaQuery.of(Get.context!).size.height;
  }

  // ------------------------------------------------------------------
  // screenWidth মেথড - স্ক্রিনের প্রস্থ রিটার্ন করে
  // ------------------------------------------------------------------
  static double screenWidth() {
    return MediaQuery.of(Get.context!).size.width;
  }

  // ------------------------------------------------------------------
  // getFormattedDate মেথড - DateTime কে ফরম্যাটেড স্ট্রিংয়ে রূপান্তর করে
  // ------------------------------------------------------------------
  // প্যারামিটার:
  // - date: ফরম্যাট করার তারিখ
  // - format: তারিখ ফরম্যাট (ডিফল্ট: 'dd MMM yyyy')
  // রিটার্ন: ফরম্যাট করা তারিখ স্ট্রিং
  // ------------------------------------------------------------------
  static String getFormattedDate(DateTime date,
      {String format = 'dd MMM yyyy'}) {
    return DateFormat(format).format(date);
  }

  // ------------------------------------------------------------------
  // removeDuplicates মেথড - লিস্ট থেকে ডুপ্লিকেট আইটেম সরিয়ে দেয়
  // ------------------------------------------------------------------
  // প্যারামিটার:
  // - list: ডুপ্লিকেট মুক্ত করার লিস্ট
  // রিটার্ন: ডুপ্লিকেট মুক্ত নতুন লিস্ট
  // টাইপ প্যারামিটার: T (যেকোনো টাইপ)
  // ------------------------------------------------------------------
  static List<T> removeDuplicates<T>(List<T> list) {
    return list.toSet().toList();
  }

  // ------------------------------------------------------------------
  // wrapWidgets মেথড - Widget লিস্টকে Row-এ রূপান্তর করে
  // ------------------------------------------------------------------
  // প্যারামিটার:
  // - widgets: রূপান্তর করার Widget লিস্ট
  // - rowSize: প্রতি Row-এ সর্বোচ্চ কতটি Widget থাকবে
  // রিটার্ন: Row-এ মোড়ানো Widget লিস্ট
  // ব্যবহার: গ্রিড/কলাম ভিউ তৈরি করার জন্য
  // ------------------------------------------------------------------
  static List<Widget> wrapWidgets(List<Widget> widgets, int rowSize) {
    final wrappedList = <Widget>[];
    for (var i = 0; i < widgets.length; i += rowSize) {
      final rowChildren = widgets.sublist(
        i,
        i + rowSize > widgets.length ? widgets.length : i + rowSize,
      );
      wrappedList.add(Row(children: rowChildren));
    }
    return wrappedList;
  }
}
